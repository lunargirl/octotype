function missingMarks(text: string): string[] {
  const missing: string[] = [];
  const withoutDash = text.replaceAll("--", "");
  if (!text.includes(",")) missing.push("comma");
  if (!text.includes(".")) missing.push("period");
  if (!text.includes(";")) missing.push("semicolon");
  if (!text.includes(":")) missing.push("colon");
  if (!text.includes("--")) missing.push("dash");
  if (!text.includes("(") || !text.includes(")")) missing.push("parentheses");
  if (!text.includes('"')) missing.push("quote");
  if (!text.includes("'")) missing.push("apostrophe");
  if (!withoutDash.includes("-")) missing.push("hyphen");
  if (!text.includes("/")) missing.push("slash");
  return missing;
}

function assertDictionary(entries: DictionaryEntry[]): void {
  const problems: string[] = [];
  if (entries.length < 100) {
    problems.push(`Expected at least 100 dictionary entries, found ${entries.length}.`);
  }
  const ids = new Set<string>();
  const words = new Set<string>();
  let punctuationCount = 0;
  const typeable = /^[\n\x20-\x7E]+$/;
  for (const entry of entries) {
    if (ids.has(entry.id)) problems.push(`Duplicate id: ${entry.id}`);
    if (words.has(entry.word)) problems.push(`Duplicate word: ${entry.word}`);
    ids.add(entry.id);
    words.add(entry.word);
    if (!entry.definition.endsWith(".")) {
      problems.push(`${entry.id} definition should end with a period.`);
    }
    for (const field of [entry.definition, entry.example, entry.pronunciationAscii, entry.punctuation]) {
      if (field && !typeable.test(field)) {
        problems.push(`${entry.id} has a non-typeable character in a typing field.`);
      }
    }
    if (entry.synonyms?.some((synonym) => !typeable.test(synonym))) {
      problems.push(`${entry.id} has a non-typeable synonym.`);
    }
    if (entry.punctuation) {
      punctuationCount += 1;
      const missing = missingMarks(entry.punctuation);
      if (missing.length > 0) {
        problems.push(`${entry.id} punctuation is missing: ${missing.join(", ")}`);
      }
    }
  }
  if (punctuationCount < 40) {
    problems.push(`Expected at least 40 punctuation passages, found ${punctuationCount}.`);
  }
  for (const word of REQUIRED) {
    if (!words.has(word)) problems.push(`Missing required word: ${word}`);
  }
  if (problems.length > 0) throw new Error(problems.join("\n"));
}

